const SVG_W = 667;
const SVG_H = 777;
const LNG_MIN = 68;
const LAT_MAX = 37;
const PX_PER_LNG = SVG_W / 30;
const PX_PER_LAT = SVG_H / 31;

function toSvg(lat: number, lng: number) {
  return { x: (lng - LNG_MIN) * PX_PER_LNG, y: (LAT_MAX - lat) * PX_PER_LAT };
}

function computeViewBox(lat: number, lng: number) {
  const c = toSvg(lat, lng);
  const w = SVG_W * 0.6;
  const h = SVG_H * 0.6;
  let x = Math.max(0, Math.min(c.x - w / 2, SVG_W - w));
  let y = Math.max(0, Math.min(c.y - h / 2, SVG_H - h));
  return `${x.toFixed(0)} ${y.toFixed(0)} ${w.toFixed(0)} ${h.toFixed(0)}`;
}

